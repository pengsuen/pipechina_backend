def catalog():
    result: list[dict[str, Any]] = []
    version_counts = [4, 3, 3, 2, 2, 1]
    for (kind, topics), nversions in zip(TOPICS.items(), version_counts, strict=True):
        for i, topic in enumerate(topics):
            ordinal = len(result)
            station, station_code, owner = STATIONS[ordinal % 6]
            result.append(
                dict(
                    kind=kind,
                    index=i + 1,
                    ordinal=ordinal,
                    topic=topic,
                    code=f"QH-{PREFIX[kind]}-2025-{i + 1:03d}",
                    title=station + topic[0],
                    station=station,
                    station_code=station_code,
                    owner=owner,
                    versions=2 if i < nversions else 1,
                )
            )
    return result


